import { format } from 'prettier';
import { readFileSync, writeFileSync } from 'node:fs';
const presets = JSON.parse(
  readFileSync(
    new URL('../src/foundations/tokens/presets.json', import.meta.url),
  ),
);
const block = (tokens) =>
  Object.entries(tokens)
    .map(([key, value]) => `  --fn-${key}: ${value};`)
    .join('\n');
const foundations = {
  'font-sans': 'Manrope, system-ui, sans-serif',
  'font-heading': "Georgia, 'Times New Roman', serif",
  'font-mono': 'ui-monospace, monospace',
  'text-sm': '0.75rem',
  'text-md': '0.875rem',
  'text-lg': '1rem',
  'radius-sm': '5px',
  'radius-md': '6px',
  'radius-lg': '12px',
  'shadow-overlay': '0 30px 100px #0008',
  duration: '150ms',
  'z-overlay': '100',
  'space-1': '4px',
  'space-2': '8px',
  'space-3': '12px',
  'space-4': '16px',
  'space-6': '24px',
  'space-8': '32px',
  'breakpoint-mobile': '800px',
};
let css =
  '/* Generated by scripts/generate-tokens.mjs. No reset or page styles. */\n:root {\n' +
  block({ ...foundations, ...presets['fieldnotes-dark'].tokens }) +
  '\n}\n';
for (const [name, preset] of Object.entries(presets))
  css += `[data-fn-theme="${name}"] {\n${block(preset.tokens)}\n  color-scheme: ${preset.colorScheme};\n}\n`;
writeFileSync(
  new URL('../src/styles/tokens.css', import.meta.url),
  await format(css, { parser: 'css' }),
);
