import { format } from 'prettier';
import { readFileSync, writeFileSync } from 'node:fs';
const presets = JSON.parse(
  readFileSync(
    new URL('../src/foundations/tokens/presets.json', import.meta.url),
  ),
);
const block = (tokens) =>
  Object.entries(tokens)
    .map(([key, value]) => `  --fn-${key}: ${value};`)
    .join('\n');
const foundations = {
  'font-sans': 'Manrope, system-ui, sans-serif',
  'font-heading': "Georgia, 'Times New Roman', serif",
  'font-mono': 'ui-monospace, monospace',
  'text-sm': '0.75rem',
  'text-md': '0.875rem',
  'text-lg': '1rem',
  'radius-sm': '5px',
  'radius-md': '6px',
  'radius-lg': '12px',
  'shadow-overlay': '0 30px 100px #0008',
  duration: '150ms',
  'z-overlay': '100',
  'space-1': '4px',
  'space-2': '8px',
  'space-3': '12px',
  'space-4': '16px',
  'space-6': '24px',
  'space-8': '32px',
  'breakpoint-mobile': '800px',
  'breakpoint-wide': '1300px',
  'border-width': '1px',
  'focus-width': '2px',
  'focus-offset': '3px',
  'line-height-body': '1.8',
  'line-height-heading': '1.2',
  'font-weight-body': '400',
  'font-weight-strong': '650',
  'shadow-card': '0 1px 2px #0001',
  'z-base': '0',
  'z-sticky': '30',
  'z-tooltip': '110',
  ease: 'ease-out',
};
let css =
  '/* Generated by scripts/generate-tokens.mjs. No reset or page styles. */\n:root {\n' +
  block(foundations) +
  '\n}\n';
for (const [name, preset] of Object.entries(presets)) {
  // Share the fallback values with the explicit dark scope. Nested scopes still
  // declare their complete palette, so a parent theme cannot leak through.
  if (name === 'fieldnotes-dark') {
    css += `:root, [data-fn-theme="${name}"] {\n${block(preset.tokens)}\n}\n[data-fn-theme="${name}"] { color-scheme: ${preset.colorScheme}; }\n`;
    continue;
  }
  css += `[data-fn-theme="${name}"] {\n${block(preset.tokens)}\n  color-scheme: ${preset.colorScheme};\n}\n`;
}
writeFileSync(
  new URL('../src/styles/tokens.css', import.meta.url),
  await format(css, { parser: 'css', singleQuote: true }),
);
